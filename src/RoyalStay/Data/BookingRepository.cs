using System.Data;
using Microsoft.Data.SqlClient;
using RoyalStay.Models;

namespace RoyalStay.Data;

public record BookingResult(bool Success, string Message, int BookingId = 0);

public class BookingRepository
{
    public const int MaxNights = 30;

    private readonly string _cs;

    public BookingRepository(IConfiguration config)
    {
        _cs = config.GetConnectionString("DefaultConnection")
            ?? throw new InvalidOperationException("DefaultConnection missing in appsettings.json");
    }

    /// <summary>
    /// Creates a booking inside one SERIALIZABLE transaction:
    /// lock room row -> check capacity -> check overlap -> find/create guest user -> insert booking.
    /// The BookingId is generated by SQL Server (IDENTITY) and returned with OUTPUT INSERTED.
    /// The total is calculated here from the DB price and the number of nights (never trusted from the form).
    /// </summary>
    public BookingResult Create(int roomId, string guestName, string guestEmail, string guestPhone,
                                DateTime checkIn, DateTime checkOut, int guests)
    {
        checkIn = checkIn.Date;
        checkOut = checkOut.Date;
        guestName = guestName.Trim();
        guestEmail = guestEmail.Trim().ToLowerInvariant();
        guestPhone = guestPhone.Trim();

        if (checkIn < DateTime.Today)
            return new BookingResult(false, "Check-in date cannot be in the past.");
        if (checkOut <= checkIn)
            return new BookingResult(false, "Check-out must be after check-in.");
        if ((checkOut - checkIn).Days > MaxNights)
            return new BookingResult(false, $"You can book at most {MaxNights} nights at a time.");
        if (guests < 1)
            return new BookingResult(false, "At least 1 guest is required.");

        using var conn = new SqlConnection(_cs);
        conn.Open();
        using var tx = conn.BeginTransaction(IsolationLevel.Serializable);

        try
        {
            // 1) Lock the room row so two people cannot book the same room at the same moment.
            decimal price;
            int capacity;
            using (var cmd = new SqlCommand(
                @"SELECT Price, Capacity
                  FROM dbo.Rooms WITH (UPDLOCK, HOLDLOCK)
                  WHERE RoomId = @RoomId AND IsAvailable = 1", conn, tx))
            {
                cmd.Parameters.Add("@RoomId", SqlDbType.Int).Value = roomId;
                using var rd = cmd.ExecuteReader();
                if (!rd.Read())
                {
                    rd.Close();
                    tx.Rollback();
                    return new BookingResult(false, "Room not found or unavailable.");
                }
                price = rd.GetDecimal(0);
                capacity = rd.GetInt32(1);
            }

            if (guests > capacity)
            {
                tx.Rollback();
                return new BookingResult(false, $"This room allows a maximum of {capacity} guest(s).");
            }

            // 2) Overlap check (back-to-back stays are allowed: check-out day = next check-in day).
            if (HasOverlap(conn, tx, roomId, checkIn, checkOut, excludeBookingId: 0))
            {
                tx.Rollback();
                return new BookingResult(false, "Room is already booked for these dates.");
            }

            // 3) Find or create the guest user (guests cannot log in: placeholder hash never verifies).
            int userId;
            using (var cmd = new SqlCommand(
                @"SELECT UserId FROM dbo.Users WITH (UPDLOCK, HOLDLOCK) WHERE Email = @Email", conn, tx))
            {
                cmd.Parameters.Add("@Email", SqlDbType.NVarChar, 150).Value = guestEmail;
                var existing = cmd.ExecuteScalar();
                if (existing != null && existing != DBNull.Value)
                {
                    userId = Convert.ToInt32(existing);
                }
                else
                {
                    using var insertUser = new SqlCommand(
                        @"INSERT INTO dbo.Users (FullName, Email, PasswordHash, Role)
                          OUTPUT INSERTED.UserId
                          VALUES (@Name, @Email, @PasswordHash, @Role)", conn, tx);
                    insertUser.Parameters.Add("@Name", SqlDbType.NVarChar, 200).Value = guestName;
                    insertUser.Parameters.Add("@Email", SqlDbType.NVarChar, 150).Value = guestEmail;
                    insertUser.Parameters.Add("@PasswordHash", SqlDbType.NVarChar, 256).Value = "BOOKING_ONLY_NO_LOGIN";
                    insertUser.Parameters.Add("@Role", SqlDbType.NVarChar, 50).Value = "Guest";
                    userId = Convert.ToInt32(insertUser.ExecuteScalar());
                }
            }

            // 4) Insert booking; total = nights x price.
            decimal totalAmount = (checkOut - checkIn).Days * price;
            int newId;
            using (var cmd = new SqlCommand(
                @"INSERT INTO dbo.Bookings
                    (UserId, RoomId, GuestName, GuestEmail, GuestPhone, CheckIn, CheckOut, Guests, TotalAmount, Status)
                  OUTPUT INSERTED.BookingId
                  VALUES
                    (@UserId, @RoomId, @GuestName, @GuestEmail, @GuestPhone, @CheckIn, @CheckOut, @Guests, @TotalAmount, @Status)",
                conn, tx))
            {
                cmd.Parameters.Add("@UserId", SqlDbType.Int).Value = userId;
                cmd.Parameters.Add("@RoomId", SqlDbType.Int).Value = roomId;
                cmd.Parameters.Add("@GuestName", SqlDbType.NVarChar, 200).Value = guestName;
                cmd.Parameters.Add("@GuestEmail", SqlDbType.NVarChar, 150).Value = guestEmail;
                cmd.Parameters.Add("@GuestPhone", SqlDbType.NVarChar, 20).Value = guestPhone;
                cmd.Parameters.Add("@CheckIn", SqlDbType.Date).Value = checkIn;
                cmd.Parameters.Add("@CheckOut", SqlDbType.Date).Value = checkOut;
                cmd.Parameters.Add("@Guests", SqlDbType.Int).Value = guests;
                var amount = cmd.Parameters.Add("@TotalAmount", SqlDbType.Decimal);
                amount.Precision = 18; amount.Scale = 2; amount.Value = totalAmount;
                cmd.Parameters.Add("@Status", SqlDbType.NVarChar, 30).Value = BookingStatus.Pending;
                newId = Convert.ToInt32(cmd.ExecuteScalar());
            }

            tx.Commit();
            return new BookingResult(true, "Booking successful!", newId);
        }
        catch
        {
            try { tx.Rollback(); } catch { /* already completed */ }
            throw;
        }
    }

    private static bool HasOverlap(SqlConnection conn, SqlTransaction tx, int roomId,
                                   DateTime checkIn, DateTime checkOut, int excludeBookingId)
    {
        using var cmd = new SqlCommand(
            @"SELECT COUNT(*)
              FROM dbo.Bookings
              WHERE RoomId = @RoomId
                AND BookingId <> @ExcludeId
                AND Status <> 'Cancelled'
                AND CheckIn < @CheckOut
                AND CheckOut > @CheckIn", conn, tx);
        cmd.Parameters.Add("@RoomId", SqlDbType.Int).Value = roomId;
        cmd.Parameters.Add("@ExcludeId", SqlDbType.Int).Value = excludeBookingId;
        cmd.Parameters.Add("@CheckIn", SqlDbType.Date).Value = checkIn;
        cmd.Parameters.Add("@CheckOut", SqlDbType.Date).Value = checkOut;
        return Convert.ToInt32(cmd.ExecuteScalar()) > 0;
    }

    private const string ListSql =
        @"SELECT b.BookingId, b.RoomId, r.RoomNumber, r.RoomType, b.GuestName, b.GuestEmail, b.GuestPhone,
                 b.CheckIn, b.CheckOut, b.Guests, b.TotalAmount, b.Status, b.CreatedAt
          FROM dbo.Bookings b
          INNER JOIN dbo.Rooms r ON r.RoomId = b.RoomId";

    private static Booking Map(SqlDataReader rd) => new()
    {
        BookingId = rd.GetInt32(0),
        RoomId = rd.GetInt32(1),
        RoomNumber = rd.GetString(2),
        RoomType = rd.GetString(3),
        GuestName = rd.GetString(4),
        GuestEmail = rd.GetString(5),
        GuestPhone = rd.IsDBNull(6) ? null : rd.GetString(6),
        CheckIn = rd.GetDateTime(7),
        CheckOut = rd.GetDateTime(8),
        Guests = rd.GetInt32(9),
        TotalAmount = rd.GetDecimal(10),
        Status = rd.GetString(11),
        CreatedAt = rd.GetDateTime(12)
    };

    /// <summary>Admin list. Optional status filter.</summary>
    public List<Booking> GetAll(string? status = null)
    {
        var list = new List<Booking>();
        var sql = ListSql + (status != null ? " WHERE b.Status = @Status" : "") + " ORDER BY b.BookingId";
        using var conn = new SqlConnection(_cs);
        using var cmd = new SqlCommand(sql, conn);
        if (status != null) cmd.Parameters.Add("@Status", SqlDbType.NVarChar, 30).Value = status;
        conn.Open();
        using var rd = cmd.ExecuteReader();
        while (rd.Read()) list.Add(Map(rd));
        return list;
    }

    /// <summary>One booking, only if the email matches (used by the confirmation page).</summary>
    public Booking? GetByIdAndEmail(int bookingId, string email)
    {
        using var conn = new SqlConnection(_cs);
        using var cmd = new SqlCommand(
            ListSql + " WHERE b.BookingId = @Id AND b.GuestEmail = @Email", conn);
        cmd.Parameters.Add("@Id", SqlDbType.Int).Value = bookingId;
        cmd.Parameters.Add("@Email", SqlDbType.NVarChar, 150).Value = email.Trim().ToLowerInvariant();
        conn.Open();
        using var rd = cmd.ExecuteReader();
        return rd.Read() ? Map(rd) : null;
    }

    public record DashboardStats(int Rooms, int AvailableRooms, int Bookings, int Pending, int Confirmed, int Cancelled, decimal Revenue);

    /// <summary>Counts for the admin dashboard. Revenue = Confirmed + Completed bookings.</summary>
    public DashboardStats GetStats()
    {
        using var conn = new SqlConnection(_cs);
        using var cmd = new SqlCommand(
            @"SELECT
                (SELECT COUNT(*) FROM dbo.Rooms),
                (SELECT COUNT(*) FROM dbo.Rooms WHERE IsAvailable = 1),
                (SELECT COUNT(*) FROM dbo.Bookings),
                (SELECT COUNT(*) FROM dbo.Bookings WHERE Status = 'Pending'),
                (SELECT COUNT(*) FROM dbo.Bookings WHERE Status = 'Confirmed'),
                (SELECT COUNT(*) FROM dbo.Bookings WHERE Status = 'Cancelled'),
                (SELECT ISNULL(SUM(TotalAmount), 0) FROM dbo.Bookings WHERE Status IN ('Confirmed','Completed'))", conn);
        conn.Open();
        using var rd = cmd.ExecuteReader();
        rd.Read();
        return new DashboardStats(rd.GetInt32(0), rd.GetInt32(1), rd.GetInt32(2), rd.GetInt32(3),
                                  rd.GetInt32(4), rd.GetInt32(5), rd.GetDecimal(6));
    }

    /// <summary>Guest lookup: only bookings made with this email AND this phone number (both entered at booking time).</summary>
    public List<Booking> GetByEmailAndPhone(string email, string phone)
    {
        var list = new List<Booking>();
        using var conn = new SqlConnection(_cs);
        using var cmd = new SqlCommand(
            ListSql + " WHERE b.GuestEmail = @Email AND b.GuestPhone = @Phone ORDER BY b.CreatedAt DESC, b.BookingId DESC", conn);
        cmd.Parameters.Add("@Email", SqlDbType.NVarChar, 150).Value = email.Trim().ToLowerInvariant();
        cmd.Parameters.Add("@Phone", SqlDbType.NVarChar, 20).Value = phone.Trim();
        conn.Open();
        using var rd = cmd.ExecuteReader();
        while (rd.Read()) list.Add(Map(rd));
        return list;
    }

    /// <summary>
    /// Admin status change. Re-activating a Cancelled booking re-checks for overlaps,
    /// so a cancelled booking cannot silently create a double-booking.
    /// </summary>
    public BookingResult UpdateStatus(int bookingId, string newStatus)
    {
        if (!BookingStatus.IsValid(newStatus))
            return new BookingResult(false, "Invalid status.");

        using var conn = new SqlConnection(_cs);
        conn.Open();
        using var tx = conn.BeginTransaction(IsolationLevel.Serializable);
        try
        {
            int roomId;
            DateTime checkIn, checkOut;
            string oldStatus;
            using (var cmd = new SqlCommand(
                @"SELECT RoomId, CheckIn, CheckOut, Status
                  FROM dbo.Bookings WITH (UPDLOCK, HOLDLOCK)
                  WHERE BookingId = @Id", conn, tx))
            {
                cmd.Parameters.Add("@Id", SqlDbType.Int).Value = bookingId;
                using var rd = cmd.ExecuteReader();
                if (!rd.Read())
                {
                    rd.Close();
                    tx.Rollback();
                    return new BookingResult(false, "Booking not found.");
                }
                roomId = rd.GetInt32(0);
                checkIn = rd.GetDateTime(1);
                checkOut = rd.GetDateTime(2);
                oldStatus = rd.GetString(3);
            }

            if (oldStatus == BookingStatus.Cancelled && newStatus != BookingStatus.Cancelled
                && HasOverlap(conn, tx, roomId, checkIn, checkOut, bookingId))
            {
                tx.Rollback();
                return new BookingResult(false,
                    "Cannot re-activate: the room has been booked by someone else for these dates.");
            }

            using (var cmd = new SqlCommand(
                "UPDATE dbo.Bookings SET Status = @Status WHERE BookingId = @Id", conn, tx))
            {
                cmd.Parameters.Add("@Status", SqlDbType.NVarChar, 30).Value = newStatus;
                cmd.Parameters.Add("@Id", SqlDbType.Int).Value = bookingId;
                cmd.ExecuteNonQuery();
            }

            tx.Commit();
            return new BookingResult(true, $"Booking #{bookingId:0000} is now {newStatus}.", bookingId);
        }
        catch
        {
            try { tx.Rollback(); } catch { /* already completed */ }
            throw;
        }
    }
}